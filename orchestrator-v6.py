# ---------- main ----------
def main():
    parser = argparse.ArgumentParser(
        description="Orchestrate analysis + normalization pipeline (v6)"
    )
    parser.add_argument("--analyze", action="store_true")
    parser.add_argument("--normalize", action="store_true")
    parser.add_argument("--input-folder", default="data/json/products_by_id")
    parser.add_argument("--analysis-output", default="analysis_output")
    parser.add_argument("--normalized-output", default="normalized_output")
    parser.add_argument(
        "--max-files", type=int, help="Limit number of gz files to process (streaming)"
    )
    parser.add_argument("--analyzer-batch-size", type=int, default=50)
    parser.add_argument(
        "--workers", type=int, default=4, help="Number of threads for normalizer"
    )
    parser.add_argument("--no-progress", action="store_true")
    parser.add_argument(
        "--tag-csv", help="If provided, skip analyzer -> use this tag CSV"
    )
    parser.add_argument(
        "--type-csv", help="If provided, skip analyzer -> use this type CSV"
    )
    parser.add_argument(
        "--report-dir", default="reports", help="Where to save HTML reports"
    )

    args = parser.parse_args()

    log_dir = Path("logs")
    logger = setup_orch_logger(log_dir)

    run_id = datetime.now().strftime("%Y%m%d_%H%M%S")
    start_time = datetime.now().isoformat()

    tag_csv = args.tag_csv
    type_csv = args.type_csv

    analyzer_info = {}
    normalizer_info = {}

    # ---------- ANALYZER ----------
    if args.analyze:
        logger.info("Starting analyzer...")
        analyzer = ProductAnalyzer(
            input_folder=args.input_folder,
            output_dir=args.analysis_output,
        )

        # Try the streaming signature first; fall back to older signature if necessary.
        try:
            analyzer_res = analyzer.run_analysis(
                max_files=args.max_files, show_progress=not args.no_progress
            )
        except TypeError:
            logger.info(
                "Analyzer.run_analysis signature mismatch — falling back to older signature names."
            )
            # older implementations used: run_analysis(source="disk", max_products=..., batch_size=...)
            try:
                analyzer_res = analyzer.run_analysis(
                    source="disk",
                    max_products=args.max_files,
                    batch_size=args.analyzer_batch_size,
                )
            except Exception as e:
                logger.error(f"Analyzer fallback failed: {e}")
                raise

        # normalize analyzer result keys
        tag_csv = analyzer_res.get("tag_csv") or tag_csv
        type_csv = analyzer_res.get("type_csv") or type_csv

        # try to discover analyzer log
        analyzer_log = None
        ao = Path(args.analysis_output)
        if ao.exists():
            logs = sorted(ao.glob("optimus_v4_analyzer_*.log"), reverse=True)
            if logs:
                analyzer_log = str(logs[0])

        analyzer_info = {
            "total_files": analyzer_res.get("total_files"),
            "total_products": analyzer_res.get("total_products"),
            "tag_csv": tag_csv,
            "type_csv": type_csv,
            "log_file": analyzer_log,
        }
        logger.info(f"Analyzer finished. tag_csv={tag_csv} type_csv={type_csv}")

    # ---------- NORMALIZER ----------
    if args.normalize:
        # ensure we have CSVs
        if not tag_csv or not type_csv:
            ap = Path(args.analysis_output)
            if ap.exists():
                tag_matches = sorted(ap.glob("tag_analysis_*.csv"), reverse=True)
                type_matches = sorted(ap.glob("type_analysis_*.csv"), reverse=True)
                if tag_matches and not tag_csv:
                    tag_csv = str(tag_matches[0])
                if type_matches and not type_csv:
                    type_csv = str(type_matches[0])

        if not tag_csv or not type_csv:
            logger.error(
                "Tag or Type CSV not found. Run analyzer first or provide --tag-csv and --type-csv."
            )
            return

        logger.info("Starting normalizer...")
        normalizer = ProductNormalizer(
            output_dir=args.normalized_output,
            input_folder=args.input_folder,
        )

        # Try the streaming multithreaded signature first; fall back to process_all older signature.
        try:
            norm_res = normalizer.process_all_stream(
                tag_csv=tag_csv,
                type_csv=type_csv,
                input_folder=args.input_folder,
                workers=args.workers,
                max_files=args.max_files,
                update_supabase=False,
                show_progress=not args.no_progress,
            )
        except TypeError:
            logger.info(
                "Normalizer.process_all_stream signature missing — falling back to older process_all."
            )
            try:
                # older signature: process_all(tag_csv, type_csv, max_products=..., batch_size=..., update_supabase=...)
                norm_res = normalizer.process_all(
                    tag_csv=tag_csv,
                    type_csv=type_csv,
                    source="disk",
                    input_folder=args.input_folder,
                    max_products=args.max_files,
                    batch_size=args.analyzer_batch_size,
                    update_supabase=False,
                )
            except Exception as e:
                logger.error(f"Normalizer fallback failed: {e}")
                raise

        # discover normalizer log
        normalizer_log = None
        no = Path(args.normalized_output)
        if no.exists():
            logs = sorted(no.glob("optimus_v4_normalizer_*.log"), reverse=True)
            if logs:
                normalizer_log = str(logs[0])

        normalizer_info = {
            "total_files": norm_res.get("total_files"),
            "total_products": norm_res.get("total_products"),
            "output_dir": str(Path(args.normalized_output).resolve()),
            "log_file": normalizer_log,
        }
        logger.info(
            f"Normalizer finished. files={normalizer_info.get('total_files')} products={normalizer_info.get('total_products')}"
        )

    if not args.analyze and not args.normalize:
        logger.info("Nothing to run. Use --analyze and/or --normalize.")
        return

    # ---------- HTML report ----------
    end_time = datetime.now().isoformat()
    report_dir = Path(args.report_dir)
    report_dir.mkdir(parents=True, exist_ok=True)
    report_file = report_dir / f"run_report_{run_id}.html"
    report_data = {
        "run_id": run_id,
        "start_time": start_time,
        "end_time": end_time,
        "analyzer": analyzer_info,
        "normalizer": normalizer_info,
        "notes": "Run generated by orchestrator-v6.py (compat fallback enabled).",
    }
    generate_html_report(report_file, report_data)
    logger.info(f"HTML report written to: {report_file}")


if __name__ == "__main__":
    main()
