#!/usr/bin/env python3
"""
orchestrator-v6.py

Orchestrator wrapper that runs analyzer then normalizer (or either).
This version is tolerant of differing method signatures:
- It tries the newer streaming signatures (max_files, show_progress, process_all_stream)
  and falls back to older signatures (max_products, batch_size, process_all) when needed.

Usage examples:
  python orchestrator-v6.py --analyze --normalize --workers 2
  python orchestrator-v6.py --analyze
  python orchestrator-v6.py --normalize --tag-csv path/to/tag.csv --type-csv path/to/type.csv
"""

import argparse
import logging
from pathlib import Path
from datetime import datetime
from logging.handlers import TimedRotatingFileHandler

# Local module imports - ensure these files are in same folder or on PYTHONPATH
try:
    from optimus_v4 import ProductAnalyzer
    from optimus_v4_normalizer import ProductNormalizer
except Exception as e:
    print(f"Failed to import modules: {e}")
    raise


# ---------- basic logging for orchestrator ----------
def setup_orch_logger(log_dir: Path):
    logger = logging.getLogger("orchestrator")
    logger.setLevel(logging.INFO)
    if logger.handlers:
        return logger
    fmt = logging.Formatter(
        "%(asctime)s %(levelname)s: %(message)s", "%Y-%m-%dT%H:%M:%S%z"
    )
    ch = logging.StreamHandler()
    ch.setFormatter(fmt)
    logger.addHandler(ch)
    log_dir.mkdir(parents=True, exist_ok=True)
    fh = TimedRotatingFileHandler(
        str(log_dir / f"orchestrator_{datetime.now().strftime('%Y%m%d_%H%M%S')}.log"),
        when="midnight",
        backupCount=7,
    )
    fh.setFormatter(fmt)
    logger.addHandler(fh)
    return logger


# ---------- small HTML report functions ----------
def link_or_path(v):
    if not v:
        return "—"
    p = Path(v)
    if p.exists():
        # return relative link text
        return f'<a href="{p.as_posix()}">{p.name}</a>'
    return f"{v}"


